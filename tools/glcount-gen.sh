#!/bin/bash
# GL call counting for diagnosis (build-torcs.sh GLCOUNT=1).
#   tools/glcount-gen.sh OUTDIR FILE...   (objects and archives to be linked)
# Lists every gl[A-Z]* function those files call and writes, in OUTDIR:
#   glcount.s     __wrap_glX for each: count the call, then go on to
#                 __real_glX (no registers changed, so any arguments and
#                 the VFP registers pass through as they are);
#   glcount.c     the names, the counters and riscos_glcount_report(),
#                 which riscostrace.cpp calls if it's linked in: the calls
#                 since the last report, total and the most-called;
#   glcount.ld    the -Wl,--wrap options, one per line.
set -euo pipefail
OUT=$1; shift
mkdir -p "$OUT"
arm-riscos-gnueabihf-nm -u "$@" 2>/dev/null | awk '$1 == "U" && $2 ~ /^gl[A-Z]/ {print $2}' | sort -u > "$OUT/glcount.names"
n=$(wc -l < "$OUT/glcount.names")
[ "$n" -gt 0 ] || { echo "glcount: no GL functions found" >&2; exit 1; }
{
  echo "@ Generated by tools/glcount-gen.sh: count each GL call, then make it."
  echo "	.syntax unified"
  echo "	.arm"
  echo "	.text"
  i=0
  while read -r f; do
    cat <<ASM
	.global __wrap_$f
	.type __wrap_$f, %function
__wrap_$f:
	push	{r0, r1}
	ldr	r0, =glcount_counts+$((i * 4))
	ldr	r1, [r0]
	add	r1, r1, #1
	str	r1, [r0]
	pop	{r0, r1}
	b	__real_$f
	.ltorg
ASM
    i=$((i + 1))
  done < "$OUT/glcount.names"
} > "$OUT/glcount.s"
{
  echo "/* Generated by tools/glcount-gen.sh. */"
  echo "#include <stdio.h>"
  echo "#define GLCOUNT_N $n"
  echo "unsigned glcount_counts[GLCOUNT_N];"
  echo "static const char *const glcount_names[GLCOUNT_N] = {"
  sed 's/.*/  "&",/' "$OUT/glcount.names"
  echo "};"
  cat <<'C'
/* Calls that wait for an answer (a round trip through RISC3D). */
static int glcount_waits(const char *n)
{
	return n[2] == 'G' && n[3] == 'e' && n[4] == 't' ? 1 :	/* glGet... */
	       n[2] == 'I' && n[3] == 's' ? 1 :			/* glIs... */
	       n[2] == 'R' && n[3] == 'e' && n[4] == 'a' && n[5] == 'd' && n[6] == 'P' ? 1 : /* glReadPixels */
	       n[2] == 'F' && n[3] == 'i' && n[4] == 'n' && n[5] == 'i' ? 1 : 0;	/* glFinish */
}

void riscos_glcount_report(const char *label, unsigned frames)
{
	static unsigned last[GLCOUNT_N];
	unsigned d[GLCOUNT_N], total = 0, waits = 0;
	int i, k, top[12], ntop = 0;
	for (i = 0; i < GLCOUNT_N; i++) {
		d[i] = glcount_counts[i] - last[i];
		last[i] = glcount_counts[i];
		total += d[i];
		if (glcount_waits(glcount_names[i])) {
			waits += d[i];
		}
	}
	for (k = 0; k < 12; k++) {
		int best = -1;
		for (i = 0; i < GLCOUNT_N; i++) {
			int used = 0, j;
			for (j = 0; j < ntop; j++) {
				if (top[j] == i) used = 1;
			}
			if (!used && d[i] > 0 && (best < 0 || d[i] > d[best])) best = i;
		}
		if (best < 0) break;
		top[ntop++] = best;
	}
	if (frames > 0) {
		printf("  GL calls, %s: %u (%u a frame), %u that wait for an answer (%u a frame)\n",
		       label, total, total / frames, waits, waits / frames);
	} else {
		printf("  GL calls, %s: %u, %u that wait for an answer\n", label, total, waits);
	}
	for (k = 0; k < ntop; k++) {
		printf("    %-28s %9u%s\n", glcount_names[top[k]], d[top[k]],
		       glcount_waits(glcount_names[top[k]]) ? "  (waits)" : "");
	}
	fflush(stdout);
}
C
} > "$OUT/glcount.c"
sed 's/.*/-Wl,--wrap=&/' "$OUT/glcount.names" > "$OUT/glcount.ld"
echo "glcount: $n GL functions wrapped"
